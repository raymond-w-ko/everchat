CREATE TABLE `everchat_wake` (
  `chat` bigint(20) NOT NULL,
  `n` bigint(20) NOT NULL,
  `text` text NOT NULL,
  `cron` varchar(256) DEFAULT NULL,
  `at` bigint(20) DEFAULT NULL,
  `zone` varchar(128) NOT NULL,
  `first` bigint(20) NOT NULL,
  `turn` bigint(20) DEFAULT NULL,
  `call` bigint(20) DEFAULT NULL,
  `due` bigint(20) DEFAULT NULL,
  `slot` bigint(20) DEFAULT NULL,
  `pending` bigint(20) DEFAULT NULL,
  `missed` int(11) NOT NULL DEFAULT 0,
  `fired` int(11) NOT NULL DEFAULT 0,
  `last_turn` bigint(20) DEFAULT NULL,
  `settled` tinyint(4) NOT NULL DEFAULT 1,
  `failed` int(11) NOT NULL DEFAULT 0,
  `stopped` bigint(20) DEFAULT NULL,
  `why` varchar(16) DEFAULT NULL,
  `stop_call` bigint(20) DEFAULT NULL,
  `created` bigint(20) NOT NULL,
  `updated` bigint(20) NOT NULL,
  PRIMARY KEY (`chat`,`n`),
  KEY `everchat_wake_due` (`chat`,`due`),
  KEY `everchat_wake_turn_fk` (`chat`,`turn`),
  KEY `everchat_wake_call_fk` (`chat`,`call`),
  KEY `everchat_wake_last_turn_fk` (`chat`,`last_turn`),
  KEY `everchat_wake_stop_call_fk` (`chat`,`stop_call`),
  CONSTRAINT `everchat_wake_call_fk` FOREIGN KEY (`chat`, `call`) REFERENCES `everchat_call` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_wake_chat_fk` FOREIGN KEY (`chat`) REFERENCES `everchat_chat` (`id`) ON DELETE CASCADE,
  CONSTRAINT `everchat_wake_last_turn_fk` FOREIGN KEY (`chat`, `last_turn`) REFERENCES `everchat_turn` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_wake_stop_call_fk` FOREIGN KEY (`chat`, `stop_call`) REFERENCES `everchat_call` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_wake_turn_fk` FOREIGN KEY (`chat`, `turn`) REFERENCES `everchat_turn` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_wake_ck1` CHECK (`missed` >= 0),
  CONSTRAINT `everchat_wake_ck2` CHECK (`fired` >= 0),
  CONSTRAINT `everchat_wake_ck3` CHECK (`settled` in (0,1)),
  CONSTRAINT `everchat_wake_ck4` CHECK (`failed` >= 0),
  CONSTRAINT `everchat_wake_ck5` CHECK (`why` in ('fired','unwake','person','failed')),
  CONSTRAINT `everchat_wake_ck6` CHECK (`cron` is null <> (`at` is null)),
  CONSTRAINT `everchat_wake_ck7` CHECK (`at` is null or `first` = `at`),
  CONSTRAINT `everchat_wake_ck8` CHECK (`turn` is null = (`call` is null)),
  CONSTRAINT `everchat_wake_ck9` CHECK (`stopped` is null = (`why` is null)),
  CONSTRAINT `everchat_wake_ck10` CHECK (`stop_call` is null or `why` is not null and `why` = 'unwake'),
  CONSTRAINT `everchat_wake_ck11` CHECK (`stopped` is null or `due` is null and `pending` is null),
  CONSTRAINT `everchat_wake_ck12` CHECK (`pending` is null or `slot` is null or `pending` > `slot`),
  CONSTRAINT `everchat_wake_ck13` CHECK (`last_turn` is not null or `settled` = 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_nopad_bin ROW_FORMAT=DYNAMIC;
