CREATE TABLE `everchat_approval` (
  `chat` bigint(20) NOT NULL,
  `n` bigint(20) NOT NULL,
  `turn` bigint(20) NOT NULL,
  `call` bigint(20) NOT NULL,
  `fn` varchar(64) NOT NULL,
  `input` longtext NOT NULL,
  `status` varchar(16) NOT NULL,
  `who` varchar(256) DEFAULT NULL,
  `answer` longtext DEFAULT NULL,
  `answered` bigint(20) DEFAULT NULL,
  `output` longtext DEFAULT NULL,
  `ended` bigint(20) DEFAULT NULL,
  `msg` bigint(20) DEFAULT NULL,
  `created` bigint(20) NOT NULL,
  `updated` bigint(20) NOT NULL,
  PRIMARY KEY (`chat`,`n`),
  UNIQUE KEY `everchat_approval_call` (`chat`,`call`),
  KEY `everchat_approval_pending` (`chat`,`status`),
  KEY `everchat_approval_turn_fk` (`chat`,`turn`),
  KEY `everchat_approval_msg_fk` (`chat`,`msg`),
  CONSTRAINT `everchat_approval_call_fk` FOREIGN KEY (`chat`, `call`) REFERENCES `everchat_call` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_approval_chat_fk` FOREIGN KEY (`chat`) REFERENCES `everchat_chat` (`id`) ON DELETE CASCADE,
  CONSTRAINT `everchat_approval_msg_fk` FOREIGN KEY (`chat`, `msg`) REFERENCES `everchat_msg` (`chat`, `i`) ON DELETE CASCADE,
  CONSTRAINT `everchat_approval_turn_fk` FOREIGN KEY (`chat`, `turn`) REFERENCES `everchat_turn` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_approval_ck1` CHECK (`status` in ('pending','yes','no','expired','running','done','failed','cut')),
  CONSTRAINT `everchat_approval_ck2` CHECK (`status` = 'pending' = (`answered` is null)),
  CONSTRAINT `everchat_approval_ck3` CHECK (`status` in ('done','failed','cut') = (`ended` is not null)),
  CONSTRAINT `everchat_approval_ck4` CHECK (`status` <> 'expired' or `who` is null)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_nopad_bin ROW_FORMAT=DYNAMIC;
