CREATE TABLE `everchat_usage` (
  `chat` bigint(20) NOT NULL,
  `n` bigint(20) NOT NULL,
  `served` varchar(16) NOT NULL,
  `turn` bigint(20) DEFAULT NULL,
  `node_l` bigint(20) DEFAULT NULL,
  `node_i` bigint(20) DEFAULT NULL,
  `pick` bigint(20) NOT NULL,
  `request` varchar(255) DEFAULT NULL,
  `input` bigint(20) NOT NULL,
  `cache_read` bigint(20) NOT NULL,
  `cache_write` bigint(20) NOT NULL,
  `output` bigint(20) NOT NULL,
  `searches` bigint(20) NOT NULL DEFAULT 0,
  `micros` bigint(20) DEFAULT NULL,
  `created` bigint(20) NOT NULL,
  `expected` bigint(20) DEFAULT NULL,
  PRIMARY KEY (`chat`,`n`),
  KEY `everchat_usage_pick_fk` (`pick`),
  KEY `everchat_usage_turn_fk` (`chat`,`turn`),
  CONSTRAINT `everchat_usage_chat_fk` FOREIGN KEY (`chat`) REFERENCES `everchat_chat` (`id`) ON DELETE CASCADE,
  CONSTRAINT `everchat_usage_pick_fk` FOREIGN KEY (`pick`) REFERENCES `everchat_pick` (`id`),
  CONSTRAINT `everchat_usage_turn_fk` FOREIGN KEY (`chat`, `turn`) REFERENCES `everchat_turn` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_usage_ck1` CHECK (`served` in ('turn','compaction','goal'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_nopad_bin ROW_FORMAT=DYNAMIC;
