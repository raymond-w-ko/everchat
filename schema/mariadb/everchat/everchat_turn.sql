CREATE TABLE `everchat_turn` (
  `chat` bigint(20) NOT NULL,
  `n` bigint(20) NOT NULL,
  `agent` bigint(20) DEFAULT NULL,
  `status` varchar(16) NOT NULL,
  `pick` bigint(20) NOT NULL,
  `head` bigint(20) NOT NULL,
  `first_msg` bigint(20) NOT NULL,
  `launch` bigint(20) NOT NULL,
  `created` bigint(20) NOT NULL,
  `ended` bigint(20) DEFAULT NULL,
  `why` mediumtext DEFAULT NULL,
  `steps` int(11) DEFAULT NULL,
  `tokens` bigint(20) DEFAULT NULL,
  PRIMARY KEY (`chat`,`n`),
  KEY `everchat_turn_running` (`chat`,`status`),
  KEY `everchat_turn_pick_fk` (`pick`),
  KEY `everchat_turn_head_fk` (`chat`,`head`),
  KEY `everchat_turn_launch_fk` (`chat`,`launch`),
  CONSTRAINT `everchat_turn_chat_fk` FOREIGN KEY (`chat`) REFERENCES `everchat_chat` (`id`) ON DELETE CASCADE,
  CONSTRAINT `everchat_turn_head_fk` FOREIGN KEY (`chat`, `head`) REFERENCES `everchat_head` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_turn_launch_fk` FOREIGN KEY (`chat`, `launch`) REFERENCES `everchat_launch` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_turn_pick_fk` FOREIGN KEY (`pick`) REFERENCES `everchat_pick` (`id`),
  CONSTRAINT `everchat_turn_ck1` CHECK (`status` in ('running','done','stopped','failed')),
  CONSTRAINT `everchat_turn_ck2` CHECK (`steps` > 0),
  CONSTRAINT `everchat_turn_ck3` CHECK (`tokens` > 0),
  CONSTRAINT `everchat_turn_ck4` CHECK (`status` = 'running' = (`ended` is null)),
  CONSTRAINT `everchat_turn_ck5` CHECK (`steps` is null = (`tokens` is null))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_nopad_bin ROW_FORMAT=DYNAMIC;
