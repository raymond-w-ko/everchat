CREATE TABLE `everchat_msg` (
  `chat` bigint(20) NOT NULL,
  `i` bigint(20) NOT NULL,
  `kind` tinyint(4) NOT NULL,
  `text` mediumtext NOT NULL,
  `size` bigint(20) NOT NULL,
  `more` tinyint(4) NOT NULL DEFAULT 0,
  `line` text DEFAULT NULL,
  `turn` bigint(20) DEFAULT NULL,
  `call` bigint(20) DEFAULT NULL,
  `sender_key` varchar(128) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `launch` bigint(20) NOT NULL,
  `created` bigint(20) NOT NULL,
  PRIMARY KEY (`chat`,`i`),
  UNIQUE KEY `everchat_msg_sender_key` (`chat`,`sender_key`),
  KEY `everchat_msg_kind_fk` (`kind`),
  KEY `everchat_msg_turn_fk` (`chat`,`turn`),
  KEY `everchat_msg_call_fk` (`chat`,`call`),
  KEY `everchat_msg_launch_fk` (`chat`,`launch`),
  CONSTRAINT `everchat_msg_call_fk` FOREIGN KEY (`chat`, `call`) REFERENCES `everchat_call` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_msg_chat_fk` FOREIGN KEY (`chat`) REFERENCES `everchat_chat` (`id`) ON DELETE CASCADE,
  CONSTRAINT `everchat_msg_kind_fk` FOREIGN KEY (`kind`) REFERENCES `everchat_kind` (`id`),
  CONSTRAINT `everchat_msg_launch_fk` FOREIGN KEY (`chat`, `launch`) REFERENCES `everchat_launch` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_msg_turn_fk` FOREIGN KEY (`chat`, `turn`) REFERENCES `everchat_turn` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_msg_ck1` CHECK (`more` in (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_nopad_bin ROW_FORMAT=DYNAMIC;
