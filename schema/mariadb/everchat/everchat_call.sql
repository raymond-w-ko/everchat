CREATE TABLE `everchat_call` (
  `chat` bigint(20) NOT NULL,
  `n` bigint(20) NOT NULL,
  `turn` bigint(20) NOT NULL,
  `parent` bigint(20) DEFAULT NULL,
  `vendor_id` varchar(255) DEFAULT NULL,
  `fn` varchar(64) NOT NULL,
  `input` longtext NOT NULL,
  `output` longtext DEFAULT NULL,
  `size` bigint(20) DEFAULT NULL,
  `shown` bigint(20) DEFAULT NULL,
  `status` varchar(16) NOT NULL,
  `pgid` int(11) DEFAULT NULL,
  `launch` bigint(20) NOT NULL,
  `created` bigint(20) NOT NULL,
  `ended` bigint(20) DEFAULT NULL,
  PRIMARY KEY (`chat`,`n`),
  UNIQUE KEY `everchat_call_vendor` (`chat`,`turn`,`vendor_id`),
  KEY `everchat_call_parent` (`chat`,`parent`),
  KEY `everchat_call_running` (`chat`,`status`),
  KEY `everchat_call_launch_fk` (`chat`,`launch`),
  CONSTRAINT `everchat_call_chat_fk` FOREIGN KEY (`chat`) REFERENCES `everchat_chat` (`id`) ON DELETE CASCADE,
  CONSTRAINT `everchat_call_launch_fk` FOREIGN KEY (`chat`, `launch`) REFERENCES `everchat_launch` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_call_parent_fk` FOREIGN KEY (`chat`, `parent`) REFERENCES `everchat_call` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_call_turn_fk` FOREIGN KEY (`chat`, `turn`) REFERENCES `everchat_turn` (`chat`, `n`) ON DELETE CASCADE,
  CONSTRAINT `everchat_call_ck1` CHECK (`status` in ('running','done','failed','denied','cut','pending')),
  CONSTRAINT `everchat_call_ck2` CHECK (`parent` is null = (`vendor_id` is not null)),
  CONSTRAINT `everchat_call_ck3` CHECK (`status` = 'running' = (`ended` is null))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_nopad_bin ROW_FORMAT=DYNAMIC;
